const preMigration137 = [...simulatedPumps, ...simulatedTanks, ...simulatedFacilities];
assert(preMigration137.length === 137, 'Pre-migration data contains exactly 137 records', preMigration137.length, 137);

// Count duplicates before migration
const duplicatesBefore = preMigration137.filter((r, idx) => 
  preMigration137.findIndex(other => other.requestNumber === r.requestNumber) !== idx
).length;
console.log(`[DIAGNOSTIC] Duplicate request numbers before migration: ${duplicatesBefore} duplicates across sections`);

// Execute ONE-TIME Migration
const migrationResult = normalizeAndRenumberMaintenanceRequests(preMigration137);

assert(
  migrationResult.totalRecords === 137,
  'Migration: Preserved all 137 records without deleting any record',
  migrationResult.totalRecords,
  137
);

assert(
  migrationResult.sectionStats['pumps'].minNumber === 1 && migrationResult.sectionStats['pumps'].maxNumber === 46,
  'Migration: Pumps sequence is 1..46',
  `${migrationResult.sectionStats['pumps'].minNumber}..${migrationResult.sectionStats['pumps'].maxNumber}`,
  '1..46'
);

assert(
  migrationResult.sectionStats['tanks'].minNumber === 1 && migrationResult.sectionStats['tanks'].maxNumber === 46,
  'Migration: Tanks sequence is 1..46',
  `${migrationResult.sectionStats['tanks'].minNumber}..${migrationResult.sectionStats['tanks'].maxNumber}`,
  '1..46'
);

assert(
  migrationResult.sectionStats['facilities'].minNumber === 1 && migrationResult.sectionStats['facilities'].maxNumber === 45,
  'Migration: Facilities sequence is 1..45',
  `${migrationResult.sectionStats['facilities'].minNumber}..${migrationResult.sectionStats['facilities'].maxNumber}`,
  '1..45'
);

// Verify Pumps next request after 46
const nextPumpsAfter46 = getNextMaintenanceRequestNumber(migrationResult.normalized, 'pumps');
assert(nextPumpsAfter46 === '47', 'Next Pumps request after 46 records is 47', nextPumpsAfter46, '47');

// Verify Tanks next request after 46
const nextTanksAfter46 = getNextMaintenanceRequestNumber(migrationResult.normalized, 'tanks');
assert(nextTanksAfter46 === '47', 'Next Tanks request after 46 records is 47', nextTanksAfter46, '47');

// -------------------------------------------------------------
// TEST 5: Deletion of Pumps Request 20
// -------------------------------------------------------------
const dbAfterDelete20 = migrationResult.normalized.filter(r => !(r.section === 'pumps' && r.requestNumber === '20'));
const nextPumpsAfterDelete = getNextMaintenanceRequestNumber(dbAfterDelete20, 'pumps');
assert(
  nextPumpsAfterDelete === '47',
  'Test 5: After deleting Pumps request 20, next request does NOT reuse 20 and remains 47',
  nextPumpsAfterDelete,
  '47'
);

// -------------------------------------------------------------
// TEST 6: Rapid Consecutive Request Creation in Pumps
// -------------------------------------------------------------
const req1 = getNextMaintenanceRequestNumber(migrationResult.normalized, 'pumps'); // 47
const dbWithReq1 = [
  { ...migrationResult.normalized[0], id: 'new-p-47', section: 'pumps' as const, requestNumber: req1 },
  ...migrationResult.normalized
];
const req2 = getNextMaintenanceRequestNumber(dbWithReq1, 'pumps'); // 48
assert(
  req1 === '47' && req2 === '48',
  'Test 6: Rapid consecutive creations in Pumps receive unique sequential IDs (47 then 48)',
  `${req1}, ${req2}`,
  '47, 48'
);

// -------------------------------------------------------------
// TEST 7: Excel Export Verification (Per Section)
// -------------------------------------------------------------
const pumpsExcel = migrationResult.normalized.filter(r => r.section === 'pumps');
const tanksExcel = migrationResult.normalized.filter(r => r.section === 'tanks');
const facExcel = migrationResult.normalized.filter(r => r.section === 'facilities');

const uniquePumpsExport = new Set(pumpsExcel.map(r => r.requestNumber)).size;
const uniqueTanksExport = new Set(tanksExcel.map(r => r.requestNumber)).size;
const uniqueFacExport = new Set(facExcel.map(r => r.requestNumber)).size;

assert(
  pumpsExcel.length === 46 && uniquePumpsExport === 46 &&
  tanksExcel.length === 46 && uniqueTanksExport === 46 &&
  facExcel.length === 45 && uniqueFacExport === 45,
  'Test 7: Excel export has independent sequences per section (Pumps: 1..46, Tanks: 1..46, Facilities: 1..45) with 0 duplicates within each section',
  `${uniquePumpsExport}, ${uniqueTanksExport}, ${uniqueFacExport}`,
  '46, 46, 45'
);

console.log('\n================================================================');
console.log(`TEST SUMMARY: ${passedTests}/${totalTests} tests passed.`);
console.log('================================================================\n');

if (passedTests === totalTests) {
  console.log('ALL TESTS PASSED WITH 100% SUCCESS!');
} else {
  console.error('FAILURES DETECTED!');
  process.exit(1);
}
